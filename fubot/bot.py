"""Funções utilitárias do fubot."""


def greet(name):
    """Devolve uma saudação para ``name``."""
    return f"Olá, {name}!"


def add(a, b):
    """Soma dois números e devolve o resultado."""
    return a + b


def shout(text):
    """Devolve ``text`` em maiúsculas com um ponto de exclamação no final."""
    return f"{text.upper()}!"
